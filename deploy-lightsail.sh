#!/usr/bin/env bash
# ============================================================================
#  NECTRA — one-shot installer for AWS Lightsail (Ubuntu)
#
#  Run it AFTER cloning the repo, as the default `ubuntu` user:
#
#      git clone https://github.com/demigod412/nectra.git
#      cd nectra
#      bash deploy-lightsail.sh
#
#  What it does:
#    • installs Node.js 22, nginx, ufw
#    • installs the app's dependencies
#    • creates a .env with a generated MASTER_KEY (kept on re-runs)
#    • runs NECTRA as a systemd service (auto-restart, starts on boot)
#    • puts nginx in front as an HTTPS reverse proxy
#    • sets up SSL for Cloudflare WITHOUT any Cloudflare API:
#         1) you paste a Cloudflare Origin Certificate  -> SSL mode "Full (strict)"
#         2) or it auto-generates a self-signed cert     -> SSL mode "Full"
#    • restores the real visitor IP from Cloudflare and (optionally) only
#      accepts traffic from Cloudflare's IP ranges
#
#  You still point your domain's DNS at this server IN CLOUDFLARE (A record,
#  orange cloud ON). No Cloudflare API token is needed anywhere.
# ============================================================================
set -euo pipefail

# ---- pretty output ----------------------------------------------------------
c()  { printf '\033[1;35m%s\033[0m\n' "$*"; }    # heading (pink)
ok() { printf '\033[1;32m✓ %s\033[0m\n' "$*"; }  # success
warn(){ printf '\033[1;33m! %s\033[0m\n' "$*"; } # warning
die(){ printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] && die "Run this as the normal 'ubuntu' user (not root / not sudo). It will use sudo itself where needed."
command -v sudo >/dev/null || die "sudo is required."

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
[ -f "$APP_DIR/package.json" ] || die "Run this from inside the cloned NECTRA repo (package.json not found next to the script)."
APP_USER="$(id -un)"
SERVICE=nectra
NODE_MAJOR=22
PORT=3000

c "NECTRA installer — $APP_DIR (user: $APP_USER)"

# ---- prompts ----------------------------------------------------------------
read -rp "Domain to serve NECTRA on (e.g. app.example.com): " DOMAIN
DOMAIN="$(echo "${DOMAIN:-}" | tr -d ' ')"
[ -n "$DOMAIN" ] || die "A domain is required."

read -rp "Run in DEMO mode on first boot? (shows codes on-screen, simulates chain actions — handy for a first test) [Y/n]: " DEMO
DEMO=${DEMO:-Y}; case "$DEMO" in [Nn]*) DEMO_MODE=0;; *) DEMO_MODE=1;; esac

echo
echo "SSL / Cloudflare — how should the origin (this server) present HTTPS?"
echo "  1) I'll paste a Cloudflare Origin Certificate   -> use Cloudflare SSL mode: Full (strict)   [recommended]"
echo "  2) Auto-generate a self-signed certificate      -> use Cloudflare SSL mode: Full"
read -rp "Choose [1/2]: " SSLOPT; SSLOPT=${SSLOPT:-2}

read -rp "Lock the firewall so ONLY Cloudflare's IPs can reach this server? [y/N]: " CFONLY
CFONLY=${CFONLY:-N}

# ============================================================================
c "1/7  System packages"
sudo apt-get update -y
sudo apt-get install -y ca-certificates curl gnupg openssl ufw git
if ! command -v node >/dev/null || [ "$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)" -lt "$NODE_MAJOR" ]; then
  c "    installing Node.js ${NODE_MAJOR}.x"
  curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | sudo -E bash -
  sudo apt-get install -y nodejs
fi
sudo apt-get install -y nginx
ok "node $(node -v) · npm $(npm -v) · $(nginx -v 2>&1)"

# ============================================================================
c "2/7  App dependencies"
cd "$APP_DIR"
if [ -f package-lock.json ]; then npm ci --omit=dev || npm install --omit=dev; else npm install --omit=dev; fi
ok "dependencies installed"

# ============================================================================
c "3/7  Environment (.env)"
if [ -f .env ]; then
  ok ".env already exists — keeping it (MASTER_KEY preserved)"
  grep -q '^PUBLIC_URL=' .env || echo "PUBLIC_URL=https://$DOMAIN" >> .env
else
  MASTER_KEY="$(openssl rand -hex 32)"
  cat > .env <<ENV
# --- NECTRA server config (generated by deploy-lightsail.sh) ---
PORT=$PORT
HOST=127.0.0.1
COOKIE_SECURE=1
TRUST_PROXY=1
DEMO_MODE=$DEMO_MODE
MASTER_KEY=$MASTER_KEY
PUBLIC_URL=https://$DOMAIN

# --- Fill these in when ready (then: sudo systemctl restart $SERVICE) ---
# ANTHROPIC_API_KEY=            # Claude Copilot (optional; rule-based parser works without it)
# SOLANA_RPC=                   # dedicated Solana RPC (recommended for live)
# RPC_ETHEREUM= RPC_BASE= RPC_ARBITRUM= RPC_BSC= RPC_POLYGON=
# TRON_API_KEY=
# SMTP_HOST= SMTP_PORT=587 SMTP_USER= SMTP_PASS= MAIL_FROM="NECTRA <no-reply@$DOMAIN>"
# NOWPAYMENTS_API_KEY= NOWPAYMENTS_IPN_SECRET=   # crypto subscription checkout
# VAPID_SUBJECT=mailto:admin@$DOMAIN
# VAPID_PUBLIC_KEY= VAPID_PRIVATE_KEY=   # web push (generate with: npx web-push generate-vapid-keys)
ENV
  chmod 600 .env
  ok ".env created with a fresh MASTER_KEY (chmod 600 — back this file up!)"
fi

# ============================================================================
c "4/7  systemd service"
sudo tee /etc/systemd/system/${SERVICE}.service >/dev/null <<UNIT
[Unit]
Description=NECTRA trading platform
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$APP_USER
WorkingDirectory=$APP_DIR
ExecStart=/usr/bin/node server/index.js
Restart=always
RestartSec=3
NoNewPrivileges=true
# allow writing only the app's own data dir
ReadWritePaths=$APP_DIR

[Install]
WantedBy=multi-user.target
UNIT
sudo systemctl daemon-reload
sudo systemctl enable "$SERVICE" >/dev/null 2>&1 || true
sudo systemctl restart "$SERVICE"
sleep 3
sudo systemctl is-active --quiet "$SERVICE" && ok "service running on 127.0.0.1:$PORT" || { sudo journalctl -u "$SERVICE" -n 30 --no-pager; die "service failed to start (logs above)."; }

# ============================================================================
c "5/7  TLS certificate for the origin"
sudo mkdir -p /etc/ssl/nectra
CRT=/etc/ssl/nectra/origin.pem
KEY=/etc/ssl/nectra/origin.key
if [ "$SSLOPT" = "1" ]; then
  echo "In Cloudflare: SSL/TLS → Origin Server → Create Certificate (leave defaults, PEM)."
  echo
  echo ">>> Paste the ORIGIN CERTIFICATE below, then press Enter and Ctrl-D:"
  sudo tee "$CRT" >/dev/null
  echo ">>> Paste the PRIVATE KEY below, then press Enter and Ctrl-D:"
  sudo tee "$KEY" >/dev/null
  [ -s "$CRT" ] && [ -s "$KEY" ] || die "Certificate or key was empty."
  CF_MODE="Full (strict)"
  ok "Cloudflare Origin certificate installed"
else
  sudo openssl req -x509 -newkey rsa:2048 -nodes -days 3650 \
    -keyout "$KEY" -out "$CRT" -subj "/CN=$DOMAIN" >/dev/null 2>&1
  CF_MODE="Full"
  ok "self-signed origin certificate generated (valid 10 years)"
fi
sudo chmod 600 "$KEY"

# real visitor IP from Cloudflare (public IP lists — no API needed)
c "    restoring real visitor IP from Cloudflare"
{
  echo "# Cloudflare edge IPs -> trust CF-Connecting-IP for the real client address"
  for ip in $(curl -fsSL https://www.cloudflare.com/ips-v4 2>/dev/null) $(curl -fsSL https://www.cloudflare.com/ips-v6 2>/dev/null); do
    echo "set_real_ip_from $ip;"
  done
  echo "real_ip_header CF-Connecting-IP;"
} | sudo tee /etc/nginx/conf.d/nectra-cloudflare-realip.conf >/dev/null
grep -q set_real_ip_from /etc/nginx/conf.d/nectra-cloudflare-realip.conf && ok "Cloudflare real-IP list installed" || warn "couldn't fetch Cloudflare IP list (real client IP may show Cloudflare's)"

# ============================================================================
c "6/7  nginx reverse proxy"
sudo tee /etc/nginx/sites-available/${SERVICE} >/dev/null <<NGINX
map \$http_upgrade \$connection_upgrade { default upgrade; '' close; }

server {
    listen 80;
    listen [::]:80;
    server_name $DOMAIN;
    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name $DOMAIN;

    ssl_certificate     $CRT;
    ssl_certificate_key $KEY;
    ssl_protocols TLSv1.2 TLSv1.3;

    client_max_body_size 12m;   # room for KYC ID uploads

    location / {
        proxy_pass http://127.0.0.1:$PORT;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$connection_upgrade;
        proxy_buffering off;          # live updates (server-sent events)
        proxy_read_timeout 1h;
    }
}
NGINX
sudo ln -sf /etc/nginx/sites-available/${SERVICE} /etc/nginx/sites-enabled/${SERVICE}
sudo rm -f /etc/nginx/sites-enabled/default
sudo nginx -t
sudo systemctl reload nginx
ok "nginx serving https://$DOMAIN -> 127.0.0.1:$PORT"

# ============================================================================
c "7/7  Firewall (ufw)"
sudo ufw allow OpenSSH >/dev/null 2>&1 || sudo ufw allow 22/tcp >/dev/null 2>&1 || true
case "$CFONLY" in
  [Yy]*)
    warn "Restricting 80/443 to Cloudflare IPs only — reach the site through your domain, not the raw IP."
    for ip in $(curl -fsSL https://www.cloudflare.com/ips-v4 2>/dev/null) $(curl -fsSL https://www.cloudflare.com/ips-v6 2>/dev/null); do
      sudo ufw allow from "$ip" to any port 80 proto tcp >/dev/null 2>&1 || true
      sudo ufw allow from "$ip" to any port 443 proto tcp >/dev/null 2>&1 || true
    done
    ;;
  *)
    sudo ufw allow 80/tcp  >/dev/null 2>&1 || true
    sudo ufw allow 443/tcp >/dev/null 2>&1 || true
    ;;
esac
sudo ufw --force enable >/dev/null 2>&1 || true
ok "ufw active"

# ============================================================================
PUBIP="$(curl -fsSL https://checkip.amazonaws.com 2>/dev/null | tr -d ' \n' || true)"
echo
c "NECTRA is up 🌸"
echo "  Service : sudo systemctl status $SERVICE   ·   logs: sudo journalctl -u $SERVICE -f"
echo "  Restart : sudo systemctl restart $SERVICE   (after editing $APP_DIR/.env)"
echo
c "Finish in Cloudflare (no API needed):"
echo "  1. DNS → add an A record:  $DOMAIN  ->  ${PUBIP:-<this server public IP>}   (Proxy status: Proxied / orange cloud ON)"
echo "  2. SSL/TLS → Overview → set encryption mode to:  $CF_MODE"
echo "  3. Also open ports 80 and 443 in the Lightsail console (Networking → IPv4 Firewall)."
echo
if [ -f "$APP_DIR/data/first-run-credentials.txt" ]; then
  c "First-run admin & demo accounts (also in data/first-run-credentials.txt):"
  sed 's/^/  /' "$APP_DIR/data/first-run-credentials.txt"
  warn "Change these passwords after your first login."
fi
echo
warn "For production: log in to /admin → Settings and turn DEMO mode OFF, set treasury addresses, and configure SMTP so email codes actually send. Back up $APP_DIR/.env (the MASTER_KEY) and data/nectra.db."
